"""Rebuild src/mcqx.js and the extra why lines from src/mcqspec/<ch>.jsonl.
Each line: ["topic","question","right",["w1","w2","w3"],"Rule: ...\\nApply: ...\\nCheck: ..."]
Topic is a lesson title. Indexes continue after the base count in tools/base.json."""
import json,glob,os
base=json.load(open('tools/base.json'))
js=["// extra multiple-choice questions, generated by tools/addmcq.py from src/mcqspec"]
for f in sorted(glob.glob('src/mcqspec/*.jsonl')):
    ch=os.path.basename(f)[:-6]; rows=[json.loads(l) for l in open(f,encoding='utf-8') if l.strip()]
    wf=f'src/why/{ch}.txt'; lines=[l.rstrip('\n') for l in open(wf,encoding='utf-8') if l.strip()][:base[ch]]
    for k,(t,q,ok,wr,why) in enumerate(rows):
        assert len(wr)==3, (ch,q)
        assert why.count('\n')>=1, (ch,q,'why needs steps')
        i=base[ch]+k; lines.append(f"{i}|{q[:30].split('|')[0]}|{why}".replace('\n','\\n'))
        js.append(f'MCQ[{json.dumps(ch)}].push(M({json.dumps(t,ensure_ascii=False)},{json.dumps(q,ensure_ascii=False)},{json.dumps(ok,ensure_ascii=False)},{json.dumps(wr,ensure_ascii=False)},{json.dumps(why.split(chr(10))[0],ensure_ascii=False)}));')
    open(wf,'w',encoding='utf-8').write('\n'.join(lines)+'\n'); print(ch,len(rows),'added')
open('src/mcqx.js','w',encoding='utf-8').write('\n'.join(js)+'\n')
